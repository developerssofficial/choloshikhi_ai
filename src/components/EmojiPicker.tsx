interface EmojiPickerProps {
  onSelect: (emoji: string) => void;
  onClose: () => void;
}

export default function EmojiPicker({ onSelect, onClose }: EmojiPickerProps) {
  const [activeCategory, setActiveCategory] = useState(0);
  const [search, setSearch] = useState("");
  const ref = useRef<HTMLDivElement>(null);

  // Close on outside click
  useEffect(() => {
    function handleClick(e: MouseEvent) {
      if (ref.current && !ref.current.contains(e.target as Node)) {
        onClose();
      }
    }
    document.addEventListener("mousedown", handleClick);
    return () => document.removeEventListener("mousedown", handleClick);
  }, [onClose]);

  const categories = EMOJI_DATA;

  // Filter emojis by search
  const filteredEmojis = search
    ? categories.flatMap((cat) => cat.emojis).filter(() => true) // show all when searching
    : categories[activeCategory]?.emojis || [];

  return (
    <div
      ref={ref}
      className="absolute bottom-full mb-2 left-0 w-[320px] bg-[#1a1a24] border border-white/[0.08] rounded-2xl shadow-2xl z-50 overflow-hidden"
    >
      {/* Category Tabs */}
      <div className="flex items-center gap-0.5 px-2 pt-2 pb-1 border-b border-white/[0.06] overflow-x-auto">
        {categories.map((cat, i) => (
          <button
            key={cat.name}
            onClick={() => { setActiveCategory(i); setSearch(""); }}
            className={`shrink-0 w-8 h-8 flex items-center justify-center rounded-lg text-sm transition-all ${
              activeCategory === i && !search
                ? "bg-violet-600/20 scale-110"
                : "hover:bg-white/[0.06]"
            }`}
            title={cat.name}
          >
            {cat.icon}
          </button>
        ))}
      </div>

      {/* Search */}
      <div className="px-2 py-1.5">
        <input
          type="text"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          placeholder="Search emoji..."
          className="w-full bg-white/[0.04] border border-white/[0.06] rounded-lg px-3 py-1.5 text-xs text-white placeholder-gray-500 focus:outline-none focus:border-violet-500/30"
        />
      </div>

      {/* Emoji Grid */}
      <div className="px-2 pb-2">
        <p className="text-[10px] text-gray-500 px-1 py-1">
          {search ? "All emojis" : categories[activeCategory]?.name}
        </p>
        <div className="grid grid-cols-8 gap-0.5 max-h-[200px] overflow-y-auto pr-1">
          {(search
            ? categories.flatMap((c) => c.emojis)
            : filteredEmojis
          ).map((emoji, i) => (
            <button
              key={`${emoji}-${i}`}
              onClick={() => {
                onSelect(emoji);
                onClose();
              }}
              className="w-8 h-8 flex items-center justify-center text-xl hover:bg-white/[0.08] rounded-lg transition-all hover:scale-110"
            >
              {emoji}
            </button>
          ))}
        </div>
      </div>
    </div>
  );
}
