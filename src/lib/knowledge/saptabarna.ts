/**
 * Searches the Saptabarna Knowledge Base to find relevant chapter context
 */
export function findSaptabarnaContext(query: string): string | null {
  const q = query.toLowerCase();

  const isAskingAboutBook =
    q.includes("সপ্তবর্ণা") ||
    q.includes("সপ্তম শ্রেণি") ||
    q.includes("class 7") ||
    q.includes("৭ম শ্রেণি") ||
    q.includes("bangla book") ||
    q.includes("বাংলা বই");

  // Check matching chapter
  const matched = SAPTABARNA_CHAPTERS.filter((ch) => {
    const titleMatch = q.includes(ch.title.toLowerCase());
    const authorMatch = q.includes(ch.author.toLowerCase());
    const idMatch = q.includes(ch.id);

    // Number matching (যেমন: ১ম অধ্যায়, প্রথম গদ্য, ৩য় কবিতা ইত্যাদি)
    const numMatch =
      (q.includes("১ম") || q.includes("প্রথম") || q.includes("1st") || q.includes("chapter 1") || q.includes("অধ্যায় ১")) && (ch.chapterNumber === 1 || ch.chapterNumber === 10);

    return titleMatch || authorMatch || idMatch || (isAskingAboutBook && numMatch);
  });

  if (matched.length > 0) {
    const ch = matched[0];
    return (
      `\n\n═══ [NCTB পাঠ্যবই তথ্যসূত্র: সপ্তবর্ণা (সপ্তম শ্রেণি বাংলা)] ═══\n` +
      `• অধ্যায়: ${ch.title} (${ch.type})\n` +
      `• লেখক/কবি: ${ch.author} (পৃষ্ঠা: ${ch.pages})\n` +
      `• সারসংক্ষেপ: ${ch.summary}\n` +
      `• মূলভাব ও শিক্ষা: ${ch.coreTheme}\n` +
      `• চরিত্র/প্রেক্ষাপট: ${ch.charactersOrContext.join(", ")}\n` +
      `• গুরুত্বপূর্ণ শব্দার্থ: ${Object.entries(ch.keyWordMeanings).map(([k, v]) => `${k} = ${v}`).join(", ")}\n` +
      `• সৃজনশীল থিম: ${ch.creativeQuestionThemes.join(", ")}\n` +
      `নির্দেশনা: তুমি শিক্ষার্থীর কাছে সপ্তবর্ণা পাঠ্যবইয়ের এই সঠিক তথ্যসূত্র ব্যবহার করে অত্যন্ত সহজ, প্রাঞ্জল ও সমৃদ্ধ বাংলায় বুঝিয়ে দাও।`
    );
  }

  // If asking general question about Saptabarna book
  if (isAskingAboutBook) {
    const proseList = SAPTABARNA_CHAPTERS.filter((c) => c.type === "গদ্য" || c.type === "নাটিকা" || c.type === "প্রবন্ধ").map((c, i) => `${i + 1}. ${c.title} (${c.author})`).join("\n");
    const poemList = SAPTABARNA_CHAPTERS.filter((c) => c.type === "কবিতা").map((c, i) => `${i + 1}. ${c.title} (${c.author})`).join("\n");

    return (
      `\n\n═══ [NCTB পাঠ্যবই তথ্যসূত্র: সপ্তবর্ণা (সপ্তম শ্রেণি বাংলা)] ═══\n` +
      `বই: সপ্তবর্ণা (সপ্তম শ্রেণি, NCTB ২০২৬ পরিমার্জিত শিক্ষাবর্ষ)\n` +
      `গদ্যসমূহ (৯টি):\n${proseList}\n\n` +
      `কবিতাসমূহ (৯টি):\n${poemList}\n` +
      `নির্দেশনা: শিক্ষার্থী সপ্তবর্ণা বইয়ের যেকোনো গল্প, কবিতা বা অধ্যায় জানতে চাইলে তুমি এই পাঠ্যবইয়ের জ্ঞানভাণ্ডার থেকে সঠিক তথ্য দিয়ে সহায়তা করো।`
    );
  }

  return null;
}
