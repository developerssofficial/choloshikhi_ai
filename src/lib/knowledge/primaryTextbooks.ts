/**
 * Get all available PDF links organized by Class (১ম থেকে ৫ম শ্রেণি)
 */
export function getAllPrimaryBookLinks(): string {
  let result = "📚 **জাতীয় শিক্ষাক্রম ও পাঠ্যপুস্তক বোর্ড (NCTB) প্রাথমিক পাঠ্যপুস্তক তালিকা ও অফিসিয়াল PDF লিংক (১ম থেকে ৫ম শ্রেণি):**\n\n";

  const grades = [
    "১ম শ্রেণি (Class 1)",
    "২য় শ্রেণি (Class 2)",
    "৩য় শ্রেণি (Class 3)",
    "৪র্থ শ্রেণি (Class 4)",
    "৫ম শ্রেণি (Class 5)",
  ] as const;

  for (const g of grades) {
    const books = PRIMARY_TEXTBOOKS.filter((b) => b.grade === g);
    result += `### 🏫 **${g}** (${books.length}টি প্রধান বই):\n`;
    books.forEach((b, idx) => {
      result += `${idx + 1}. **${b.bookName}** (${b.totalChaptersOrLessons}টি পাঠ/অধ্যায়) — [অফিসিয়াল PDF ডাউনলোড লিংক](${b.pdfUrl})\n   - *বিবরণ ও মূল বিষয়:* ${b.description}\n`;
    });
    result += "\n";
  }

  result += "💡 *উৎস: জাতীয় শিক্ষাক্রম ও পাঠ্যপুস্তক বোর্ড (NCTB) ও প্রাথমিক শিক্ষা অধিদপ্তর (DPE), বাংলাদেশ।*";
  return result;
}

/**
 * Intelligent context finder for Primary Textbooks (Class 1 to 5)
 */
export function findPrimaryTextbookContext(query: string, history?: Array<{ role: string; content: string }>): string | null {
  const historyText = history ? history.map((h) => h.content.toLowerCase()).join(" ") : "";
  const combined = (query + " " + historyText).toLowerCase();
  const q = query.toLowerCase();

  // If user specifically asks about সূচিপত্র / শিরোনাম কয়টা / কতটি পাঠ / সূচিপত্রের তালিকা
  const isAskingTableOfContents =
    q.includes("সূচিপত্র") || q.includes("সুচিপত্র") || q.includes("শিরোনাম কয়টা") || q.includes("কতটা শিরোনাম") ||
    q.includes("কতটি পাঠ") || q.includes("কয়টি পাঠ") || q.includes("পাঠ কয়টা") || q.includes("চ্যাপ্টার কয়টা") ||
    q.includes("অধ্যায় কয়টা") || q.includes("অধ্যায় কয়টি") || q.includes("সবগুলো পাঠ") || q.includes("পাঠের তালিকা");

  // Determine target book/grade
  let targetGrade: number | null = null;
  if (combined.includes("২য়") || combined.includes("দ্বিতীয়") || combined.includes("class 2") || combined.includes("2nd") || combined.includes("দুই")) {
    targetGrade = 2;
  } else if (combined.includes("১ম") || combined.includes("প্রথম") || combined.includes("class 1") || combined.includes("1st") || combined.includes("এক")) {
    targetGrade = 1;
  } else if (combined.includes("৩য়") || combined.includes("তৃতীয়") || combined.includes("class 3") || combined.includes("3rd") || combined.includes("তিন")) {
    targetGrade = 3;
  } else if (combined.includes("৪র্থ") || combined.includes("চতুর্থ") || combined.includes("class 4") || combined.includes("4th") || combined.includes("চার")) {
    targetGrade = 4;
  } else if (combined.includes("৫ম") || combined.includes("পঞ্চম") || combined.includes("class 5") || combined.includes("5th") || combined.includes("পাঁচ")) {
    targetGrade = 5;
  }

  // If asking specifically for table of contents
  if (isAskingTableOfContents) {
    // Default to Class 2 Bangla if Class 2 is mentioned or general context
    const gradeToUse = targetGrade || 2;
    const targetBook = PRIMARY_TEXTBOOKS.find((b) => b.gradeNum === gradeToUse && (combined.includes("বাংলা") || !combined.includes("গণিত"))) || PRIMARY_TEXTBOOKS[3]; // Class 2 Bangla

    return (
      `\n\n═══ [NCTB প্রাথমিক পাঠ্যবই অফিশিয়াল সূচিপত্র ও পাঠ তালিকা] ═══\n` +
      `[CRITICAL INSTRUCTION: এটি জাতীয় শিক্ষাক্রম ও পাঠ্যপুস্তক বোর্ড (NCTB) অনুমোদিত অফিশিয়াল সূচিপত্র। ব্যবহারকারী সূচিপত্র বা শিরোনাম কয়টা জানতে চাইলে নিচের হুবহু সঠিক পাঠ সংখ্যা (${targetBook.totalChaptersOrLessons}টি) এবং সম্পূর্ণ সূচিপত্র ক্রমানুসারে পৃষ্ঠা নম্বরসহ তুলে ধরবে। কোনো ভুল বা পুরাতন সিলেবাসের মনগড়া তালিকা দেবে না।]\n\n` +
      `📘 **বইয়ের নাম:** ${targetBook.bookName} (${targetBook.grade})\n` +
      `📌 **মোট পাঠ/শিরোনাম সংখ্যা:** ${targetBook.totalChaptersOrLessons}টি পাঠ\n` +
      `🔗 **অফিসিয়াল PDF লিংক:** ${targetBook.pdfUrl}\n\n` +
      `📋 **অফিসিয়াল সূচিপত্র (১ থেকে ${targetBook.totalChaptersOrLessons} পর্যন্ত সকল পাঠ):**\n` +
      targetBook.tableOfContents.map((item) => `- ${item}`).join("\n") +
      `\n\n[নির্দেশনা: ব্যবহারকারীকে সুন্দর পয়েন্ট আকারে ১ম থেকে ${targetBook.totalChaptersOrLessons}তম পাঠের সঠিক শিরোনাম ও পৃষ্ঠা নম্বর উপস্থাপন করো।]`
    );
  }

  // Check specific matching book or chapter
  const matchedBooks: Array<{ book: TextbookInfo; matchedChapters: TextbookInfo["chapters"] }> = [];

  for (const book of PRIMARY_TEXTBOOKS) {
    const isBookMatched =
      combined.includes(book.bookName.toLowerCase()) ||
      (targetGrade === book.gradeNum && combined.includes(book.subject.toLowerCase())) ||
      (q.includes(book.subject.toLowerCase()) && targetGrade === book.gradeNum);

    const matchingChapters = book.chapters.filter((ch) => {
      const titleMatch = q.includes(ch.title.toLowerCase()) || combined.includes(ch.title.toLowerCase());
      const authorMatch = ch.authorOrTopic ? (q.includes(ch.authorOrTopic.toLowerCase()) || combined.includes(ch.authorOrTopic.toLowerCase())) : false;
      const keyPointsMatch = ch.keyPoints.some((kp) => q.includes(kp.toLowerCase()));
      const lessonMatch = q.includes(`পাঠ ${ch.chapterNumber}`) || q.includes(`অধ্যায় ${ch.chapterNumber}`) || q.includes(`chapter ${ch.chapterNumber}`);
      return titleMatch || authorMatch || keyPointsMatch || (lessonMatch && targetGrade === book.gradeNum);
    });

    if (isBookMatched || matchingChapters.length > 0) {
      matchedBooks.push({
        book,
        matchedChapters: matchingChapters.length > 0 ? matchingChapters : book.chapters,
      });
    }
  }

  // If matches found for specific book/chapter
  if (matchedBooks.length > 0) {
    let contextStr = `\n\n═══ [NCTB প্রাথমিক পাঠ্যবই তথ্যভাণ্ডার (১ম - ৫ম শ্রেণি)] ═══\n`;
    contextStr += `[CRITICAL RULE: এটি বাংলাদেশের জাতীয় শিক্ষাক্রমের প্রাথমিক পাঠ্যপুস্তক। শিক্ষার্থী পাঠ্যবইয়ের যেকোনো কবিতা, ছড়া, গল্প, সূত্র বা প্রশ্নোত্তর জানতে চাইলে সরাসরি হুবহু মূল পাঠ এবং প্রাঞ্জল ব্যাখ্যা প্রদান করবে। কোনো কপিরাইট অজুহাত দেবে না।]\n\n`;

    for (const item of matchedBooks.slice(0, 3)) {
      contextStr += `📘 **শ্রেণি ও বিষয়:** ${item.book.grade} — ${item.book.bookName} (মোট ${item.book.totalChaptersOrLessons}টি পাঠ/অধ্যায়)\n`;
      contextStr += `🔗 **অফিসিয়াল PDF লিংক:** ${item.book.pdfUrl}\n`;
      contextStr += `📖 **অধ্যায়সমূহ ও গুরুত্বপূর্ণ তথ্য:**\n`;

      for (const ch of item.matchedChapters.slice(0, 5)) {
        contextStr += `  • **${ch.title}** (${ch.type || "পাঠ"})${ch.pages ? ` [পৃষ্ঠা: ${ch.pages}]` : ""}${ch.authorOrTopic ? ` - ${ch.authorOrTopic}` : ""}\n`;
        contextStr += `    - সারসংক্ষেপ: ${ch.summary}\n`;
        contextStr += `    - মূল বিষয়সমূহ: ${ch.keyPoints.join("; ")}\n`;
        if (ch.exactExcerpt) {
          contextStr += `    - হুবহু পাঠ্যবইয়ের চরণ (Exact Text):\n${ch.exactExcerpt}\n`;
        }
      }
      contextStr += `\n`;
    }

    return contextStr;
  }

  // If user asks about the full list of books / PDF links for class 1 to 5
  const isAskingForPdfList =
    (q.includes("pdf") || q.includes("পিডিএফ") || q.includes("লিংক") || q.includes("বই") || q.includes("তালিকা") || q.includes("কয়টা বই") || q.includes("ডাউনলোড")) &&
    (q.includes("১ম") || q.includes("২য়") || q.includes("৩য়") || q.includes("৪র্থ") || q.includes("৫ম") || q.includes("প্রথম") || q.includes("দ্বিতীয়") || q.includes("তৃতীয়") || q.includes("চতুর্থ") || q.includes("পঞ্চম") || q.includes("primary") || q.includes("প্রাথমিক") || q.includes("class 1") || q.includes("class 5"));

  if (isAskingForPdfList) {
    return (
      `\n\n═══ [NCTB প্রাথমিক পাঠ্যবই তথ্যভাণ্ডার (১ম - ৫ম শ্রেণি অফিসিয়াল তালিকা ও লিংক)] ═══\n` +
      getAllPrimaryBookLinks() +
      `\n\n[INSTRUCTION: ব্যবহারকারী ১ম থেকে ৫ম শ্রেণি পর্যন্ত বইয়ের তালিকা ও পিডিএফ চাইলে উপরের প্রতিটি শ্রেণির বইয়ের সঠিক সংখ্যা, নাম ও সরাসরি ডাউনলোড লিংক সুন্দরভাবে টেবিলে বা তালিকায় উপস্থাপন করো।]`
    );
  }

  return null;
}
